RealCourseContent.apply = (state, groups, directory) => {
  let changed = false;
  state.academicAdvisors ??= {};
  for (const [id, profile] of Object.entries(RealCourseContent.academicAdvisors || {})) {
    if (!state.academicAdvisors[id]) { state.academicAdvisors[id] = structuredClone(profile); changed = true; }
  }
  if (!state.kd26Imported && groups.kd26) {
    state.groupOverrides ??= {};
    groups.kd26 = {...groups.kd26, ...structuredClone(RealCourseContent.groups.kd26)};
    state.groupOverrides.kd26 = groups.kd26;
    state.kd26Imported = true;
    changed = true;
  }
  if (state.realCourseContentVersion !== RealCourseContent.version) {
    state.previousRealCourseContent ??= {};
    state.groupOverrides ??= {};
    state.staffProfiles ??= {};
    for (const [id, content] of Object.entries(RealCourseContent.groups)) {
      if (!groups[id]) continue;
      state.previousRealCourseContent[id] ??= structuredClone(groups[id]);
      groups[id] = {...groups[id], ...structuredClone(content)};
      state.groupOverrides[id] = groups[id];
    }
    for (const [id, profile] of Object.entries(RealCourseContent.staffProfiles)) {
      state.staffProfiles[id] = {...state.staffProfiles[id], ...structuredClone(profile)};
    }
    state.realCourseContentVersion = RealCourseContent.version;
    changed = true;
  }
  if (!state.welcomeArtworkRefined) {
    const group = groups.mba;
    const intro = group?.page_blocks?.find(b => b.type === 'introductions' && b.data.block_id === 'pilot-spo-intro');
    if (intro?.data.image_url === 'https://static.tildacdn.com/tild3362-6637-4938-b938-613537666336/joanna-kosinska-uGcD.jpg') {
      intro.data.image_url = '';
      intro.data.image_alt = '';
      state.groupOverrides ??= {};
      state.groupOverrides.mba = group;
    }
    state.welcomeArtworkRefined = true;
    changed = true;
  }
  if (!state.materialsCopyRefined) {
    const group = groups.mba;
    const materials = group?.page_blocks?.find(b => b.type === 'materials' && b.data.block_id === 'pilot-spo-materials');
    if (materials?.data.text === 'Дополнительные материалы группы ОНЛ_СПО-8.') {
      materials.data.text = '';
      state.groupOverrides ??= {};
      state.groupOverrides.mba = group;
    }
    state.materialsCopyRefined = true;
    changed = true;
  }
  for (const [id, name] of Object.entries(RealCourseContent.staffNames)) {
    if (directory.staff[id]) directory.staff[id].name = name;
  }
  return changed;
};
